/* ============================================================
   개인정보 판별 규칙 — 브라우저 등록 화면과 초안 생성 스크립트 공용 정본
   ------------------------------------------------------------
   같은 규칙을 두 곳에 따로 적으면 반드시 갈라진다. 그러면 등록 화면은
   "괜찮다"고 통과시켰는데 실제 글에는 동·호수가 남는 일이 생긴다.
   그래서 규칙은 이 파일 하나에만 두고,
     · 브라우저 → <script src="js/pii-rules.js"> 로 읽어 window 에서 꺼내 쓰고
     · scripts/new-case-post.mjs → 이 파일을 읽어 그대로 평가해 쓴다.
   규칙을 고칠 일이 있으면 여기만 고치면 양쪽이 같이 바뀐다.
   ============================================================ */
var MANMUL_PII_RULES = [
  ['동·호수', /(?:^|[^가-힣0-9])\d{1,4}\s*(?:동|호)(?=$|[^가-힣])/m],
  ['휴대전화', /(?:^|\D)01[016789][\s.-]?\d{3,4}[\s.-]?\d{4}(?!\d)/],
  ['일반전화', /(?:^|\D)0(?:2|[3-6][1-5])[-.\s]?\d{3,4}[-.\s]?\d{4}(?!\d)/],
  ['이메일', /[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}/i],
  ['고객명', /(?:고객명|고객\s*이름|성명|연락자|의뢰인)\s*[:=]\s*[가-힣A-Za-z]{2,30}/],
  ['고객명', /[가-힣]{2,5}\s*고객(?:님)?/],
];

if (typeof window !== 'undefined') window.MANMUL_PII_RULES = MANMUL_PII_RULES;
